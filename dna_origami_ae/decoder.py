"""
DNADecoder: a transformer-based sequence-to-sequence model that reconstructs
the original nucleotide sequence from a noisy (degraded) input sequence.

Architecture
------------
The decoder is framed as a *denoising* problem:

    noisy_sequence  →  [Transformer]  →  clean_sequence

Both the input and output are tokenised at the nucleotide level:
    vocabulary: A=0, T=1, G=2, C=3  (+ PAD=4, SOS=5, EOS=6)

The model uses a standard encoder–decoder transformer:
  - Encoder: reads the noisy sequence and builds a context representation.
  - Decoder: auto-regressively produces the clean sequence token-by-token.

Training
--------
The model is trained on pairs (noisy_sequence, clean_sequence) where noisy
sequences are generated by OrigamiSimulator with configurable error rates.
Cross-entropy loss over the output token distribution.

Inference
---------
Greedy decoding (argmax at each step) is used by default; beam search can
be enabled via the `beam_size` argument.

This module keeps the architecture small (d_model=128, 2 layers, 4 heads)
so it can run on CPU for demonstration.  Scale up as needed.

References
----------
- Vaswani et al. "Attention Is All You Need" (2017)
- Antkowiak et al. "Low Cost DNA Data Storage … with Neural Networks" (2020)
"""

from __future__ import annotations

import math
from typing import Optional

import torch
import torch.nn as nn
import torch.nn.functional as F
from torch import Tensor

# ── Vocabulary ────────────────────────────────────────────────────────────

VOCAB: dict[str, int] = {"A": 0, "T": 1, "G": 2, "C": 3, "PAD": 4, "SOS": 5, "EOS": 6}
VOCAB_INV: dict[int, str] = {v: k for k, v in VOCAB.items()}
VOCAB_SIZE = len(VOCAB)
PAD_IDX = VOCAB["PAD"]
SOS_IDX = VOCAB["SOS"]
EOS_IDX = VOCAB["EOS"]


def seq_to_tensor(seq: str) -> Tensor:
    """Convert a DNA string to a 1-D LongTensor of token indices."""
    return torch.tensor([VOCAB[b] for b in seq.upper()], dtype=torch.long)


def tensor_to_seq(t: Tensor) -> str:
    """Convert a 1-D LongTensor of token indices back to a DNA string."""
    return "".join(
        VOCAB_INV[i.item()]
        for i in t
        if i.item() not in (PAD_IDX, SOS_IDX, EOS_IDX)
    )


# ── Positional encoding ───────────────────────────────────────────────────

class PositionalEncoding(nn.Module):
    """Standard sinusoidal positional encoding."""

    def __init__(self, d_model: int, max_len: int = 2048, dropout: float = 0.1) -> None:
        super().__init__()
        self.dropout = nn.Dropout(p=dropout)
        pe = torch.zeros(max_len, d_model)
        position = torch.arange(0, max_len, dtype=torch.float).unsqueeze(1)
        div_term = torch.exp(
            torch.arange(0, d_model, 2).float() * (-math.log(10000.0) / d_model)
        )
        pe[:, 0::2] = torch.sin(position * div_term)
        pe[:, 1::2] = torch.cos(position * div_term)
        pe = pe.unsqueeze(0)  # (1, max_len, d_model)
        self.register_buffer("pe", pe)

    def forward(self, x: Tensor) -> Tensor:
        # x: (batch, seq_len, d_model)
        x = x + self.pe[:, : x.size(1)]
        return self.dropout(x)


# ── Transformer model ─────────────────────────────────────────────────────

class _DNATransformer(nn.Module):
    """Encoder–decoder transformer for DNA sequence denoising."""

    def __init__(
        self,
        d_model: int = 128,
        nhead: int = 4,
        num_encoder_layers: int = 2,
        num_decoder_layers: int = 2,
        dim_feedforward: int = 512,
        dropout: float = 0.1,
    ) -> None:
        super().__init__()
        self.d_model = d_model

        self.src_embed = nn.Embedding(VOCAB_SIZE, d_model, padding_idx=PAD_IDX)
        self.tgt_embed = nn.Embedding(VOCAB_SIZE, d_model, padding_idx=PAD_IDX)
        self.pos_enc = PositionalEncoding(d_model, dropout=dropout)

        self.transformer = nn.Transformer(
            d_model=d_model,
            nhead=nhead,
            num_encoder_layers=num_encoder_layers,
            num_decoder_layers=num_decoder_layers,
            dim_feedforward=dim_feedforward,
            dropout=dropout,
            batch_first=True,
        )
        self.out_proj = nn.Linear(d_model, VOCAB_SIZE)

    def forward(
        self,
        src: Tensor,          # (batch, src_len)
        tgt: Tensor,          # (batch, tgt_len)
        src_key_padding_mask: Optional[Tensor] = None,
        tgt_key_padding_mask: Optional[Tensor] = None,
    ) -> Tensor:
        tgt_mask = nn.Transformer.generate_square_subsequent_mask(
            tgt.size(1), device=src.device
        )
        src_emb = self.pos_enc(self.src_embed(src) * math.sqrt(self.d_model))
        tgt_emb = self.pos_enc(self.tgt_embed(tgt) * math.sqrt(self.d_model))
        out = self.transformer(
            src_emb,
            tgt_emb,
            tgt_mask=tgt_mask,
            src_key_padding_mask=src_key_padding_mask,
            tgt_key_padding_mask=tgt_key_padding_mask,
        )
        return self.out_proj(out)  # (batch, tgt_len, vocab_size)


# ── Public API ────────────────────────────────────────────────────────────

class DNADecoder:
    """Transformer-based DNA sequence denoiser.

    Quick start
    -----------
    >>> from dna_origami_ae import DNAEncoder, OrigamiSimulator, DNADecoder
    >>> enc = DNAEncoder()
    >>> sim = OrigamiSimulator(substitution_rate=0.05, seed=42)
    >>> decoder = DNADecoder(d_model=128, nhead=4)
    >>> clean = enc.encode("Hello World")
    >>> noisy = sim.simulate(clean)
    >>> decoder.train_on_pairs([(noisy, clean)] * 200, epochs=30)
    >>> recovered = decoder.decode(noisy)

    Parameters
    ----------
    d_model : int
        Transformer hidden dimension.
    nhead : int
        Number of attention heads.
    num_encoder_layers : int
        Number of transformer encoder layers.
    num_decoder_layers : int
        Number of transformer decoder layers.
    dim_feedforward : int
        Feedforward sublayer dimension.
    dropout : float
        Dropout rate.
    device : str or None
        Target device ('cpu', 'cuda', …).  Auto-detected when None.
    """

    def __init__(
        self,
        d_model: int = 128,
        nhead: int = 4,
        num_encoder_layers: int = 2,
        num_decoder_layers: int = 2,
        dim_feedforward: int = 512,
        dropout: float = 0.1,
        device: Optional[str] = None,
    ) -> None:
        self.device = torch.device(
            device or ("cuda" if torch.cuda.is_available() else "cpu")
        )
        self.model = _DNATransformer(
            d_model=d_model,
            nhead=nhead,
            num_encoder_layers=num_encoder_layers,
            num_decoder_layers=num_decoder_layers,
            dim_feedforward=dim_feedforward,
            dropout=dropout,
        ).to(self.device)

    # ── Training ─────────────────────────────────────────────────────────

    def train_on_pairs(
        self,
        pairs: list[tuple[str, str]],
        epochs: int = 50,
        lr: float = 1e-3,
        batch_size: int = 32,
        verbose: bool = True,
    ) -> list[float]:
        """Train the model on (noisy_seq, clean_seq) pairs.

        Parameters
        ----------
        pairs : list of (noisy, clean) string tuples
        epochs : int
            Number of training epochs.
        lr : float
            Learning rate for Adam optimiser.
        batch_size : int
            Mini-batch size.
        verbose : bool
            Print loss every 10 epochs.

        Returns
        -------
        list[float]
            Per-epoch average loss values.
        """
        self.model.train()
        optimiser = torch.optim.Adam(self.model.parameters(), lr=lr)
        criterion = nn.CrossEntropyLoss(ignore_index=PAD_IDX)
        losses: list[float] = []

        for epoch in range(1, epochs + 1):
            epoch_loss = 0.0
            n_batches = 0
            for start in range(0, len(pairs), batch_size):
                batch = pairs[start : start + batch_size]
                src, tgt = self._collate(batch)
                src, tgt = src.to(self.device), tgt.to(self.device)

                # Teacher forcing: feed <SOS> + tgt[:-1] as decoder input
                tgt_input = tgt[:, :-1]
                tgt_output = tgt[:, 1:]

                logits = self.model(src, tgt_input)
                # logits: (batch, tgt_len-1, vocab_size)
                loss = criterion(logits.reshape(-1, VOCAB_SIZE), tgt_output.reshape(-1))
                optimiser.zero_grad()
                loss.backward()
                torch.nn.utils.clip_grad_norm_(self.model.parameters(), 1.0)
                optimiser.step()
                epoch_loss += loss.item()
                n_batches += 1

            avg = epoch_loss / max(n_batches, 1)
            losses.append(avg)
            if verbose and (epoch % 10 == 0 or epoch == 1):
                print(f"  Epoch {epoch:3d}/{epochs}  loss={avg:.4f}")

        return losses

    # ── Inference ─────────────────────────────────────────────────────────

    @torch.no_grad()
    def decode(self, noisy_sequence: str, max_len: int = 1024) -> str:
        """Denoise *noisy_sequence* and return the reconstructed sequence.

        Uses greedy (argmax) decoding.

        Parameters
        ----------
        noisy_sequence : str
            A DNA sequence that may contain substitutions, insertions, or
            deletions introduced by :class:`OrigamiSimulator`.
        max_len : int
            Maximum output length before stopping.

        Returns
        -------
        str
            Reconstructed DNA sequence (A/T/G/C).
        """
        self.model.eval()
        src = seq_to_tensor(noisy_sequence).unsqueeze(0).to(self.device)  # (1, src_len)
        tgt_tokens = [SOS_IDX]

        for _ in range(max_len):
            tgt = torch.tensor([tgt_tokens], dtype=torch.long, device=self.device)
            logits = self.model(src, tgt)               # (1, cur_len, vocab_size)
            next_token = logits[0, -1].argmax().item()  # greedy
            if next_token == EOS_IDX:
                break
            tgt_tokens.append(next_token)

        # Remove SOS
        return tensor_to_seq(torch.tensor(tgt_tokens[1:], dtype=torch.long))

    # ── Internal helpers ──────────────────────────────────────────────────

    def _collate(
        self, pairs: list[tuple[str, str]]
    ) -> tuple[Tensor, Tensor]:
        """Tokenise and pad a batch of (noisy, clean) string pairs.

        Target sequences are wrapped with SOS and EOS tokens.
        """
        srcs = [seq_to_tensor(n) for n, _ in pairs]
        tgts = [
            torch.cat([
                torch.tensor([SOS_IDX], dtype=torch.long),
                seq_to_tensor(c),
                torch.tensor([EOS_IDX], dtype=torch.long),
            ])
            for _, c in pairs
        ]
        src_pad = nn.utils.rnn.pad_sequence(srcs, batch_first=True, padding_value=PAD_IDX)
        tgt_pad = nn.utils.rnn.pad_sequence(tgts, batch_first=True, padding_value=PAD_IDX)
        return src_pad, tgt_pad

    # ── Persistence ───────────────────────────────────────────────────────

    def save(self, path: str) -> None:
        """Save model weights to *path*."""
        torch.save(self.model.state_dict(), path)

    def load(self, path: str) -> None:
        """Load model weights from *path*."""
        self.model.load_state_dict(torch.load(path, map_location=self.device))

    def __repr__(self) -> str:
        n_params = sum(p.numel() for p in self.model.parameters())
        return f"DNADecoder(params={n_params:,}, device={self.device})"
